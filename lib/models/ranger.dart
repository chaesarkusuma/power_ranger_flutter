class Ranger {
  final String id;
  final String name;
  final String color;
  final String title;
  final String element;
  final String power;
  final String description;
  final String assetPath;
  final int powerLevel;

  const Ranger({
    required this.id,
    required this.name,
    required this.color,
    required this.title,
    required this.element,
    required this.power,
    required this.description,
    required this.assetPath,
    required this.powerLevel,
  });
}
